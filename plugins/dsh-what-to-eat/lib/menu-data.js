// 场景不是互斥的：一道菜可以同时是「家常 + 快手 + 外卖」。
// 显式声明过的按声明来，其余按标签和做法长度推断，避免每一行都要手写。
function scenesOf(tagList, recipe, explicit) {
  const s = new Set(explicit || ['家常']);
  const has = (t) => tagList.includes(t);
  // 纯外卖品（汉堡、披萨、奶茶这类）不算家常；其余都补上「家常」。
  const takeoutOnly = Boolean(explicit && explicit.includes('外卖') && !explicit.includes('家常'));
  if (!takeoutOnly) s.add('家常');
  if (has('面食') || has('米') || has('汤') || has('炸') || has('辣')) s.add('外卖');
  if (has('清淡') && !has('炸') && !has('猪肉') && !has('鸭肉') && !has('甜')) s.add('减脂');
  if (has('炸') || has('甜') || (has('猪肉') && (has('炖') || has('焖')))) s.add('放纵');
  if (has('快手') || has('拌') || has('煎')) s.add('快手');
  return [...s];
}

function shipRow(name, meals, tags, recipe, explicit) {
  // 场景词不进 tags：同一个词同时出现在「场景」和「标签」里会让界面显示两遍。
  const tagList = tags.split(',').filter((t) => !SCENE_TAGS.includes(t));
  return {
    name,
    meal: meals.split(''),
    tags: tagList,
    scene: scenesOf(tagList, recipe, explicit),
    recipe,
    guide: { url: '' },
    weight: 1,
    disabled: false,
    lastRecommendedAt: null,
    builtin: true,
    id: builtinId(name),
  };
}

