/** 稳定 id：内置条目用菜单名派生，重装/升级不会变。 */
export function builtinId(name) {
  let h = 2166136261;
  for (const ch of name) {
    h ^= ch.codePointAt(0);
    h = Math.imul(h, 16777619);
  }
  return `m${(h >>> 0).toString(36)}`;
}

